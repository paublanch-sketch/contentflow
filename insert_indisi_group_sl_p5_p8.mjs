async function insertPosts() {
  console.log(`\n➕ Insertando posts #5–#8 para INDISI GROUP SL (KENSINGTON Maresme)...\n`);

  for (const p of posts) {
    const payload = {
      id:              `${CLIENT_ID}-${p.post_number}`,
      client_id:       CLIENT_ID,
      post_number:     p.post_number,
      platform:        p.platform,
      headline_visual: p.headline_visual,
      visual_prompt:   p.visual_prompt,
      copy:            p.copy,
      hashtags:        p.hashtags,
      status:          'review',
      feedback:        '',
      image_url:       '',
      webhook_sent_at: null,
    };

    const res = await fetch(`${SUPABASE_URL}/rest/v1/posts`, {
      method: 'POST',
      headers: {
        apikey:         SUPABASE_KEY,
        Authorization:  `Bearer ${SUPABASE_KEY}`,
        'Content-Type': 'application/json',
        Prefer:         'resolution=merge-duplicates,return=representation',
      },
      body: JSON.stringify(payload),
    });

    if (!res.ok) {
      const err = await res.text();
      console.error(`❌ Post #${p.post_number}: ${err}`);
    } else {
      console.log(`✅ Post #${p.post_number} — ${p.headline_visual.substring(0, 70)}...`);
    }
  }

  console.log('\n✅ Posts #5–#8 insertats per INDISI GROUP SL');
  console.log('   → https://contentflow-4wos.vercel.app/p/indisi-group-sl');
}

